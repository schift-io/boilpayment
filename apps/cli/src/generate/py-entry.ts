// paykit/index.py generator — Python mirror of ts-entry.ts. Same selection logic; same real
// contracts verified against packages/*/py/src on 2026-09-09 (see NAMING ASSUMPTION comment
// at the top of ts-entry.ts — that note applies here too, both languages were fixed together).
//
// Python-specific calling convention (found by reading the actual .py files, not guessed):
//   - Most functions take ONE positional dataclass `input` arg (e.g. `consume(ConsumeCreditsInput(...))`).
//   - A handful take keyword-only args directly, no wrapper dataclass: usage.record, usage.check,
//     usage.flush_outbox, usage.close_period, webhook.receive, webhook.process, webhook.default_handlers.
//   - lifecycle exports `dunning` and `scheduler` as submodules (`from . import dunning, scheduler`),
//     so their Input dataclasses hang off the submodule object itself (`dunning.OnGraceExpiredInput(...)`).
import type { PaykitConfig } from '../config.js';
